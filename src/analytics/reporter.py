"""
EPIC 5: Analytics & Recommendation Engine - Automated Report Generation
Exports CSV attendance sheets, JSON analytics logs, and Markdown/HTML classroom intelligence reports.
"""

import json
from pathlib import Path
import pandas as pd
from typing import Dict, Any, List

class ClassroomReporter:
    """
    Generates structured export artifacts for educators and institutional compliance.
    """
    def __init__(self, export_dir: str = "data/logs"):
        self.export_dir = Path(export_dir)
        self.export_dir.mkdir(parents=True, exist_ok=True)

    def export_attendance_csv(self, attendance_df: pd.DataFrame, filename: str = "attendance_log.csv") -> str:
        out_path = self.export_dir / filename
        attendance_df.to_csv(out_path, index=False)
        return str(out_path)

    def export_analytics_json(self, session_data: Dict[str, Any], filename: str = "session_analytics.json") -> str:
        out_path = self.export_dir / filename
        with open(out_path, "w", encoding="utf-8") as f:
            json.dump(session_data, f, indent=2)
        return str(out_path)

    def _df_to_markdown_table(self, df: pd.DataFrame) -> str:
        """Converts DataFrame to markdown table without requiring tabulate."""
        headers = list(df.columns)
        header_row = "| " + " | ".join(headers) + " |"
        sep_row = "| " + " | ".join(["---"] * len(headers)) + " |"
        rows = []
        for _, row in df.iterrows():
            rows.append("| " + " | ".join(str(val) for val in row.values) + " |")
        return "\n".join([header_row, sep_row] + rows)

    def generate_markdown_report(
        self,
        session_id: str,
        course_name: str,
        instructor: str,
        summary_stats: Dict[str, Any],
        attendance_df: pd.DataFrame,
        suggestions: List[Dict[str, Any]],
        filename: str = "classroom_report.md"
    ) -> str:
        """
        Creates a clean Markdown evaluation report for mentors or institutional archives.
        """
        out_path = self.export_dir / filename
        table_md = self._df_to_markdown_table(attendance_df)

        md = f"""# Classroom Intelligence & Engagement Report
**Session ID:** {session_id}  
**Course:** {course_name}  
**Instructor:** {instructor}  

---

## 1. Executive Summary & Session Metrics
| Metric | Value |
| :--- | :--- |
| **Mean Engagement Score** | {summary_stats.get('mean_engagement', 0)}% |
| **Peak Engagement Score** | {summary_stats.get('peak_engagement', 0)}% |
| **Attention Drops Detected** | {summary_stats.get('total_attention_drops', 0)} |
| **Interaction Peaks** | {summary_stats.get('total_interaction_peaks', 0)} |
| **Pacing Assessment** | {summary_stats.get('pacing_index', 'Normal')} |

---

## 2. Sustained Presence Attendance Log (Scenario 1)
*Verified via continuous temporal tracking (rejecting transient walk-bys)*

{table_md}

---

## 3. AI-Driven Teaching Suggestions & Interventions (Scenario 3)
"""
        if not suggestions:
            md += "\n*No critical pedagogical interventions required. Session proceeded within optimal parameters.*\n"
        else:
            for i, sug in enumerate(suggestions, 1):
                md += f"""
### {i}. [{sug.get('priority', 'INFO')}] {sug.get('category', 'Suggestion')}
- **Timestamp:** {sug.get('timestamp', 0):.1f}s
- **Observation:** {sug.get('observation', '')}
- **Recommended Action:** {sug.get('action', '')}
- **Pedagogical Rationale:** {sug.get('pedagogical_reason', '')}
"""

        md += """
---
*Generated by Multimodal Attendance & Engagement Agent (100% Offline, Privacy-Preserving).*
"""
        with open(out_path, "w", encoding="utf-8") as f:
            f.write(md)

        return str(out_path)
